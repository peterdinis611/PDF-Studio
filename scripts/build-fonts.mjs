/**
 * Self-hosts the newsprint UI fonts.
 *
 * Copies the woff2 files we actually use out of the @fontsource packages into
 * public/fonts, and regenerates src/styles/fonts.generated.css with the exact
 * unicode-range declarations the packages ship. The ranges matter: they let the
 * browser skip latin-ext entirely on an English page.
 *
 * The editor's document font catalogue still comes from Google — those are
 * fonts the user picks for their PDF, not chrome, and there are fourteen of them.
 */
