/** Pulls the @font-face block that references `file` out of a package stylesheet. */
function readFace(pkg, cssName, file) {
  const cssPath = path.join(root, "node_modules", pkg, cssName);
  const css = fs.readFileSync(cssPath, "utf8");

  const block = css.split("@font-face").find((chunk) => chunk.includes(`/files/${file}.woff2`));
  if (!block) throw new Error(`No @font-face for ${file} in ${pkg}/${cssName}`);

  const pick = (prop) => {
    const m = block.match(new RegExp(`${prop}:\\s*([^;]+);`));
    if (!m) throw new Error(`Missing ${prop} for ${file}`);
    return m[1].trim();
  };

  return {
    style: pick("font-style"),
    weight: pick("font-weight"),
    unicodeRange: pick("unicode-range"),
    format: block.includes("woff2-variations") ? "woff2-variations" : "woff2",
    source: path.join(root, "node_modules", pkg, "files", `${file}.woff2`),
  };
}

fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });

const blocks = [];
let bytes = 0;

for (const face of FACES) {
  const { style, weight, unicodeRange, format, source } = readFace(face.pkg, face.css, face.file);
  const fileName = `${face.file}.woff2`;

  fs.copyFileSync(source, path.join(outDir, fileName));
  bytes += fs.statSync(source).size;

  blocks.push(
    [
      "@font-face {",
      `  font-family: "${face.family}";`,
      `  font-style: ${style};`,
      `  font-weight: ${weight};`,
      "  font-display: swap;",
      `  src: url("/public/fonts/${fileName}") format("${format}");`,
      `  unicode-range: ${unicodeRange};`,
      "}",
    ].join("\n"),
  );
}

const header = [
  "/*",
  " * GENERATED by scripts/build-fonts.mjs — do not edit by hand.",
  " * Run `npm run build:fonts` after changing the face list there.",
  " */",
  "",
].join("\n");

fs.writeFileSync(outCss, `${header}${blocks.join("\n\n")}\n`);

console.log(
  `fonts: ${FACES.length} faces → public/fonts (${(bytes / 1024).toFixed(0)} KB on disk)`,
);
console.log(`wrote ${path.relative(root, outCss)}`);
